const languageButton = document.querySelector("#toggle-language");
const increaseFontButton = document.querySelector("#increase-font");
const decreaseFontButton = document.querySelector("#decrease-font");
const contrastButton = document.querySelector("#toggle-contrast");
const speakButton = document.querySelector("#speak-summary");
const serviceFilter = document.querySelector("#service-filter");
const textNodes = document.querySelectorAll("[data-i18n]");

let currentLanguage = "en";
let currentFontSize = 16;

function applyLanguage(language) {
  const content = dictionary[language];
  textNodes.forEach((node) => {
    const key = node.dataset.i18n;
    if (content[key]) {
      node.textContent = content[key];
    }
  });

  languageButton.textContent = language === "en" ? "हिंदी" : "English";
  document.documentElement.lang = language === "en" ? "en" : "hi";
}

function updateFontSize(nextSize) {
  currentFontSize = Math.max(14, Math.min(22, nextSize));
  document.documentElement.style.setProperty("--font-size-base", `${currentFontSize}px`);
}

function filterServices(category) {
  const cards = document.querySelectorAll(".service-card");
  cards.forEach((card) => {
    const isVisible = category === "all" || card.dataset.category === category;
    card.classList.toggle("is-hidden", !isVisible);
  });
}

function speakSummary() {
  if (!("speechSynthesis" in window)) {
    alert("Text-to-speech is not supported in this browser.");
    return;
  }

  const summary = dictionary[currentLanguage].heroText;
  const utterance = new SpeechSynthesisUtterance(summary);
  utterance.lang = currentLanguage === "en" ? "en-IN" : "hi-IN";
  window.speechSynthesis.cancel();
  window.speechSynthesis.speak(utterance);
}

languageButton.addEventListener("click", () => {
  currentLanguage = currentLanguage === "en" ? "hi" : "en";
  applyLanguage(currentLanguage);
});

increaseFontButton.addEventListener("click", () => updateFontSize(currentFontSize + 1));
decreaseFontButton.addEventListener("click", () => updateFontSize(currentFontSize - 1));
contrastButton.addEventListener("click", () => document.body.classList.toggle("high-contrast"));
speakButton.addEventListener("click", speakSummary);
serviceFilter.addEventListener("change", (event) => filterServices(event.target.value));

applyLanguage(currentLanguage);
filterServices("all");
